import fs from 'node:fs';
import path from 'node:path';

const [packageDir, repoRoot] = process.argv.slice(2);
if (!packageDir || !repoRoot) {
  console.error('usage: node vendor-file-icons.mjs <material-icon-theme-package-dir> <repo-root>');
  process.exit(1);
}

const dist = path.join(packageDir, 'dist', 'material-icons.json');
const sourceIcons = path.join(packageDir, 'icons');
const iconsOut = path.join(repoRoot, 'apps', 'lattice', 'assets', 'file-icons');
const moduleOut = path.join(repoRoot, 'apps', 'lattice', 'src', 'file_icons.rs');
const manifest = JSON.parse(fs.readFileSync(dist, 'utf8'));

fs.rmSync(iconsOut, { recursive: true, force: true });
fs.mkdirSync(iconsOut, { recursive: true });

const definitions = new Map();
let copied = 0;
for (const [id, definition] of Object.entries(manifest.iconDefinitions)) {
  const iconPath = definition.iconPath;
  if (!iconPath) throw new Error(`icon ${id} has no iconPath`);
  const fileName = path.basename(iconPath);
  const source = path.join(sourceIcons, fileName);
  if (!fs.existsSync(source)) throw new Error(`missing svg: ${source}`);
  const destination = path.join(iconsOut, fileName);
  if (!fs.existsSync(destination)) {
    fs.copyFileSync(source, destination);
    copied += 1;
  }
  definitions.set(id, fileName);
}

for (const extra of ['LICENSE']) {
  const source = path.join(packageDir, extra);
  if (fs.existsSync(source)) {
    fs.copyFileSync(source, path.join(iconsOut, extra));
  }
}

const stableSort = (entries) =>
  entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const exactMap = (source) =>
  stableSort(
    Object.entries(source ?? {}).map(([key, icon]) => {
      if (typeof icon !== 'string') throw new Error(`invalid icon mapping for ${key}`);
      return [key.toLowerCase(), icon];
    }),
  );

const extensionMap = (source) =>
  Object.entries(source ?? {})
    .map(([key, icon]) => {
      if (typeof icon !== 'string') throw new Error(`invalid extension mapping for ${key}`);
      return [key.toLowerCase(), icon];
    })
    .sort((a, b) =>
      b[0].length - a[0].length ||
      (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0),
    );

const fileNames = exactMap(manifest.fileNames);
const fileNamesLight = exactMap(manifest.light?.fileNames);
const fileExtensions = extensionMap(manifest.fileExtensions);
const fileExtensionsLight = extensionMap(manifest.light?.fileExtensions);
const folderNames = exactMap(manifest.folderNames);
const folderNamesLight = exactMap(manifest.light?.folderNames);
const folderNamesExpanded = exactMap(manifest.folderNamesExpanded);
const folderNamesExpandedLight = exactMap(manifest.light?.folderNamesExpanded);

const entries = (pairs) =>
  pairs
    .map(([key, icon]) => {
      if (!definitions.has(icon)) throw new Error(`unknown icon id ${icon} for ${key}`);
      return `    (${JSON.stringify(key)}, ${JSON.stringify(icon)}),`;
    })
    .join('\n');

const iconArms = [...definitions.entries()]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([id, fileName]) => {
    return `        ${JSON.stringify(id)} => include_str!("../assets/file-icons/${fileName}"),`;
  })
  .join('\n');

const module = `// @generated by scripts/vendor-file-icons.mjs from material-icon-theme 5.39.0 (MIT).
// Do not edit by hand. Regenerate with:
//   node scripts/vendor-file-icons.mjs <material-icon-theme-package-dir> .
//
// The complete Material Icon Theme file/folder icon set is embedded at compile
// time. Lookup is filename-first, then longest matching extension.

const FILE_NAMES: &[(&str, &str)] = &[
${entries(fileNames)}
];

const FILE_NAMES_LIGHT: &[(&str, &str)] = &[
${entries(fileNamesLight)}
];

const FILE_EXTENSIONS: &[(&str, &str)] = &[
${entries(fileExtensions)}
];

const FILE_EXTENSIONS_LIGHT: &[(&str, &str)] = &[
${entries(fileExtensionsLight)}
];

const FOLDER_NAMES: &[(&str, &str)] = &[
${entries(folderNames)}
];

const FOLDER_NAMES_LIGHT: &[(&str, &str)] = &[
${entries(folderNamesLight)}
];

const FOLDER_NAMES_EXPANDED: &[(&str, &str)] = &[
${entries(folderNamesExpanded)}
];

const FOLDER_NAMES_EXPANDED_LIGHT: &[(&str, &str)] = &[
${entries(folderNamesExpandedLight)}
];

pub fn file_icon_svg(file_path: &str, light: bool) -> &'static str {
    svg_for_icon(file_icon_id(file_path, light))
}

fn file_icon_id(file_path: &str, light: bool) -> &'static str {
    let name = file_path.rsplit('/').next().unwrap_or(file_path).to_lowercase();
    if light
        && let Some(icon) = exact_icon(FILE_NAMES_LIGHT, &name)
            .or_else(|| extension_icon(FILE_EXTENSIONS_LIGHT, &name))
    {
        return icon;
    }
    if let Some(icon) =
        exact_icon(FILE_NAMES, &name).or_else(|| extension_icon(FILE_EXTENSIONS, &name))
    {
        return icon;
    }
    "file"
}

pub fn folder_icon_svg(folder_name: &str, expanded: bool, light: bool) -> &'static str {
    svg_for_icon(folder_icon_id(folder_name, expanded, light))
}

fn folder_icon_id(folder_name: &str, expanded: bool, light: bool) -> &'static str {
    let name = folder_name.to_lowercase();
    let expanded_map = if expanded {
        FOLDER_NAMES_EXPANDED
    } else {
        FOLDER_NAMES
    };
    let light_map = if expanded {
        FOLDER_NAMES_EXPANDED_LIGHT
    } else {
        FOLDER_NAMES_LIGHT
    };
    if light && let Some(icon) = exact_icon(light_map, &name) {
        return icon;
    }
    if let Some(icon) = exact_icon(expanded_map, &name) {
        return icon;
    }
    if expanded {
        "folderExpanded"
    } else {
        "folder"
    }
}

fn exact_icon(icons: &'static [(&'static str, &'static str)], name: &str) -> Option<&'static str> {
    icons
        .binary_search_by(|(key, _)| key.cmp(&name))
        .ok()
        .map(|index| icons[index].1)
}

fn extension_icon(
    extensions: &'static [(&'static str, &'static str)],
    name: &str,
) -> Option<&'static str> {
    for (extension, icon) in extensions {
        if name.len() <= extension.len() {
            continue;
        }
        if !name.ends_with(extension) {
            continue;
        }
        if name.as_bytes()[name.len() - extension.len() - 1] == b'.' {
            return Some(icon);
        }
    }
    None
}

fn svg_for_icon(icon: &str) -> &'static str {
    match icon {
${iconArms}
        _ => include_str!("../assets/file-icons/file.svg"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_common_source_files() {
        assert_eq!(file_icon_id("Objects/listobject.c", false), "c");
        assert_eq!(file_icon_id("Include/Python.h", false), "h");
        assert_eq!(
            file_icon_id("src/java.base/share/classes/java/util/ArrayList.java", false),
            "java"
        );
        assert_eq!(file_icon_id("README.md", false), "readme");
        assert_eq!(file_icon_id("src/main.rs", false), "rust");
        assert_eq!(file_icon_id("app.tsx", false), "react_ts");
        assert_eq!(file_icon_id("CMakeLists.txt", false), "cmake");
    }

    #[test]
    fn uses_light_variants_when_requested() {
        assert_eq!(file_icon_id("Cargo.toml", false), "toml");
        assert_eq!(file_icon_id("Cargo.toml", true), "toml_light");
    }

    #[test]
    fn folders_have_generic_and_named_icons() {
        assert_eq!(folder_icon_id("unknown-folder", false, false), "folder");
        assert_eq!(folder_icon_id("src", false, false), "folder-src");
        assert_eq!(folder_icon_id("src", true, false), "folder-src-open");
        assert!(folder_icon_svg("src", false, false).contains("viewBox"));
    }
}
`;

fs.writeFileSync(moduleOut, module, 'utf8');
console.log(
  `embedded ${definitions.size} icon definitions (${copied} svg files), ${fileNames.length} file names, ${fileExtensions.length} extensions, ${folderNames.length} folder names`,
);
